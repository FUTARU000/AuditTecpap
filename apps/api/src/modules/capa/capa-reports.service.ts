import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import ExcelJS from 'exceljs';
import { FINDING_SEVERITY_LABELS } from '@tecpap/config';
import { CapaService } from './capa.service';

@Injectable()
export class CapaReportsService {
  constructor(private readonly capaService: CapaService) {}

  async generatePdf(capaId: string): Promise<Buffer> {
    const capa = await this.capaService.snapshotForReport(capaId);
    return new Promise<Buffer>((resolve) => {
      const doc = new PDFDocument({ margin: 50, size: 'A4' });
      const chunks: Buffer[] = [];
      doc.on('data', (c: Buffer) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));

      doc.fontSize(20).fillColor('#4A3728').text('CAPA Report', { align: 'center' });
      doc.moveDown().fillColor('black').fontSize(14).text(capa.referenceNumber);
      doc.fontSize(10).fillColor('#5B8A1E').text('Corrective & Preventive Action', { align: 'center' });
      doc.moveDown().fillColor('black').fontSize(10);
      [`Title: ${capa.title}`, `Department: ${capa.department?.name ?? '—'}`, `Process: ${capa.process?.name ?? '—'}`,
       `Priority: ${capa.priority}`, `Status: ${capa.status}`, `Owner: ${capa.owner ? `${capa.owner.firstName} ${capa.owner.lastName}` : '—'}`,
       `Source: ${capa.sourceType}${capa.finding ? ` (Finding: ${capa.finding.title})` : ''}`,
       `Target Date: ${capa.targetDate?.toLocaleDateString() ?? '—'}`, `Generated: ${new Date().toLocaleString()}`].forEach((l) => doc.text(l));

      if (capa.description) { doc.moveDown().fontSize(12).text('Description'); doc.fontSize(9).text(capa.description); }
      if (capa.rootCause) {
        doc.moveDown().fontSize(12).text('Root Cause Analysis');
        doc.fontSize(9);
        if (capa.rootCause.problemStatement) doc.text(`Problem: ${capa.rootCause.problemStatement}`);
        if (capa.rootCause.immediateCause) doc.text(`Immediate Cause: ${capa.rootCause.immediateCause}`);
        if (capa.rootCause.rootCause) doc.text(`Root Cause: ${capa.rootCause.rootCause}`);
        if (capa.rootCause.contributingFactors) doc.text(`Contributing Factors: ${capa.rootCause.contributingFactors}`);
        if (capa.rootCause.useFiveWhys && capa.rootCause.whySteps.length > 0) {
          doc.moveDown(0.5).text('5 Whys Analysis:');
          capa.rootCause.whySteps.forEach((s) => doc.text(`  Why ${s.stepNumber}: ${s.question}\n  → ${s.answer ?? '—'}`));
        }
        if (capa.rootCause.useEightD && capa.rootCause.eightD) {
          doc.moveDown(0.5).text('8D Worksheet:');
          const e = capa.rootCause.eightD;
          [['D1 Team', e.d1Team], ['D2 Problem', e.d2ProblemDescription], ['D3 Interim', e.d3InterimActions], ['D4 Root Cause', e.d4RootCause], ['D5 Permanent', e.d5PermanentActions], ['D6 Implementation', e.d6Implementation], ['D7 Prevention', e.d7Prevention], ['D8 Closure', e.d8Closure]].forEach(([label, val]) => { if (val) doc.text(`  ${label}: ${val}`); });
        }
      }

      if (capa.actions.length > 0) {
        doc.moveDown().fontSize(12).text('Actions');
        capa.actions.forEach((a) => { doc.fontSize(9).text(`• [${a.actionType}] ${a.title} — ${a.status}${a.owner ? ` (${a.owner.firstName} ${a.owner.lastName})` : ''}`); if (a.completionComment) doc.text(`  Comment: ${a.completionComment}`); });
      }
      if (capa.verifications.length > 0) {
        doc.moveDown().fontSize(12).text('Verification History');
        capa.verifications.forEach((v, i) => doc.fontSize(9).text(`Attempt ${i + 1}: ${v.result} — By: ${v.verifiedBy.firstName} ${v.verifiedBy.lastName} (${v.verifiedAt.toLocaleString()})${v.notes ? `\n  Notes: ${v.notes}` : ''}`));
      }
      if (capa.effectiveness) { doc.moveDown().fontSize(12).text('Effectiveness Review'); doc.fontSize(9).text(`Result: ${capa.effectiveness.result}\nBy: ${capa.effectiveness.reviewedBy.firstName} ${capa.effectiveness.reviewedBy.lastName}\nNotes: ${capa.effectiveness.notes ?? '—'}`); }
      if (capa.closedAt) { doc.moveDown().fontSize(12).text('Closure'); doc.fontSize(9).text(`Closed: ${capa.closedAt.toLocaleDateString()}\nBy: ${capa.closedBy?.firstName ?? '—'} ${capa.closedBy?.lastName ?? ''}${capa.closureComment ? `\nComment: ${capa.closureComment}` : ''}`); }
      doc.moveDown(2).fontSize(8).fillColor('gray').text('Digitally generated by the TECPAP Audit Platform.', { align: 'center' });
      doc.end();
    });
  }

  async generateExcel(capaId: string): Promise<Buffer> {
    const capa = await this.capaService.snapshotForReport(capaId);
    const wb = new ExcelJS.Workbook();
    wb.creator = 'TECPAP Audit Platform';
    wb.created = new Date();
    const s = wb.addWorksheet('CAPA');
    s.addRow(['CAPA Report']);
    s.addRow(['Reference', capa.referenceNumber]);
    s.addRow(['Title', capa.title]);
    s.addRow(['Department', capa.department?.name ?? '—']);
    s.addRow(['Status', capa.status]);
    s.addRow(['Priority', capa.priority]);
    s.addRow(['Source', capa.sourceType]);

    const actions = wb.addWorksheet('Actions');
    actions.columns = [{ header: 'Type', key: 'type', width: 14 }, { header: 'Title', key: 'title', width: 40 }, { header: 'Owner', key: 'owner', width: 24 }, { header: 'Status', key: 'status', width: 14 }, { header: 'Due Date', key: 'due', width: 14 }];
    capa.actions.forEach((a) => actions.addRow({ type: a.actionType, title: a.title, owner: a.owner ? `${a.owner.firstName} ${a.owner.lastName}` : '—', status: a.status, due: a.dueDate?.toLocaleDateString() ?? '—' }));

    const rca = wb.addWorksheet('Root Cause');
    rca.addRow(['Problem Statement', capa.rootCause?.problemStatement ?? '—']);
    rca.addRow(['Root Cause', capa.rootCause?.rootCause ?? '—']);
    if (capa.rootCause?.whySteps) { rca.addRow([]); rca.addRow(['5 Whys']); capa.rootCause.whySteps.forEach((s) => rca.addRow([`Why ${s.stepNumber}: ${s.question}`, s.answer ?? '—'])); }

    const buffer = await wb.xlsx.writeBuffer();
    return Buffer.from(buffer);
  }
}
