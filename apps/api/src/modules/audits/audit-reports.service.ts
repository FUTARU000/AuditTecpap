import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import ExcelJS from 'exceljs';
import { FINDING_SEVERITY_LABELS } from '@tecpap/config';
import { AuditsService } from './audits.service';

/** Generates PDF / Excel audit reports. Designed to later carry digital signatures. */
@Injectable()
export class AuditReportsService {
  constructor(private readonly audits: AuditsService) {}

  async generatePdf(auditId: string): Promise<Buffer> {
    const audit = await this.audits.snapshotForReport(auditId);
    const auditorName = audit.auditor ? `${audit.auditor.firstName} ${audit.auditor.lastName}` : '—';

    return new Promise<Buffer>((resolve) => {
      const doc = new PDFDocument({ margin: 50, size: 'A4' });
      const chunks: Buffer[] = [];
      doc.on('data', (chunk: Buffer) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));

      doc.fontSize(20).fillColor('#4A3728').text('TECPAP — Audit Report', { align: 'center' });
      doc.moveDown().fillColor('black').fontSize(15).text(audit.title);
      doc.fontSize(9).fillColor('#5B8A1E').text('Quality Management System', { align: 'center' });
      doc.moveDown().fillColor('black').fontSize(10);
      [
        `Template: ${audit.template.name}`,
        `Department: ${audit.department?.name ?? '—'}`,
        `Process: ${audit.process?.name ?? '—'}`,
        `Auditor: ${auditorName}`,
        `Status: ${audit.status}`,
        `Compliance: ${audit.compliance !== null ? `${audit.compliance}%` : '—'}`,
        `Generated: ${new Date().toLocaleString()}`,
      ].forEach((line) => doc.text(line));

      doc.moveDown().fontSize(13).text('Checklist');
      for (const section of audit.template.sections) {
        doc.moveDown(0.5).fontSize(11).fillColor('#4A3728').text(section.title);
        doc.fillColor('black').fontSize(9);
        for (const question of section.questions) {
          const answer = audit.answers.find((item) => item.questionId === question.id);
          doc.text(`• ${question.text}`);
          doc.fillColor(answer?.status === 'fail' ? '#C62828' : answer?.status === 'ok' ? '#2E7D32' : 'black')
            .text(`   Answer: ${answer ? this.formatValue(answer.value) : '—'}  [${answer?.status ?? 'pending'}]`)
            .fillColor('black');
        }
      }

      doc.moveDown().fontSize(13).text('Findings');
      doc.fontSize(9);
      for (const finding of audit.findings) {
        doc.fillColor('#C62828').text(`• [${FINDING_SEVERITY_LABELS[finding.severity as keyof typeof FINDING_SEVERITY_LABELS] ?? finding.severity}] ${finding.title}`).fillColor('black');
        if (finding.description) doc.text(`   ${finding.description}`);
      }

      doc.moveDown().fontSize(13).text('Approval');
      doc.fontSize(9).text(`Approved by: ${audit.approvedBy ? `${audit.approvedBy.firstName} ${audit.approvedBy.lastName}` : '—'}`);
      if (audit.approvedAt) doc.text(`Approved at: ${audit.approvedAt.toISOString()}`);
      doc.moveDown(2).fontSize(8).fillColor('gray').text('Digitally generated by the TECPAP Audit Platform.', { align: 'center' });

      doc.end();
    });
  }

  async generateExcel(auditId: string): Promise<Buffer> {
    const audit = await this.audits.snapshotForReport(auditId);
    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'TECPAP Audit Platform';
    workbook.created = new Date();

    const info = workbook.addWorksheet('Audit');
    info.addRow(['TECPAP — Audit Report']);
    info.addRow(['Title', audit.title]);
    info.addRow(['Template', audit.template.name]);
    info.addRow(['Department', audit.department?.name ?? '—']);
    info.addRow(['Process', audit.process?.name ?? '—']);
    info.addRow(['Status', audit.status]);
    info.addRow(['Compliance', audit.compliance !== null ? `${audit.compliance}%` : '—']);

    const checklist = workbook.addWorksheet('Checklist');
    checklist.columns = [
      { header: 'Section', key: 'section', width: 28 },
      { header: 'Question', key: 'question', width: 50 },
      { header: 'Type', key: 'type', width: 16 },
      { header: 'Answer', key: 'answer', width: 30 },
      { header: 'Status', key: 'status', width: 12 },
    ];
    for (const section of audit.template.sections) {
      for (const question of section.questions) {
        const answer = audit.answers.find((item) => item.questionId === question.id);
        checklist.addRow({
          section: section.title,
          question: question.text,
          type: question.type,
          answer: answer ? this.formatValue(answer.value) : '',
          status: answer?.status ?? 'pending',
        });
      }
    }

    const findingsSheet = workbook.addWorksheet('Findings');
    findingsSheet.columns = [
      { header: 'Severity', key: 'severity', width: 24 },
      { header: 'Title', key: 'title', width: 40 },
      { header: 'Description', key: 'description', width: 50 },
      { header: 'Status', key: 'status', width: 12 },
    ];
    for (const finding of audit.findings) {
      findingsSheet.addRow({ severity: finding.severity, title: finding.title, description: finding.description ?? '', status: finding.status });
    }

    const buffer = await workbook.xlsx.writeBuffer();
    return Buffer.from(buffer);
  }

  private formatValue(value: unknown): string {
    if (value === null || value === undefined) return '—';
    if (typeof value === 'string') return value;
    return JSON.stringify(value);
  }
}
