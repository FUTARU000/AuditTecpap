import { Module } from '@nestjs/common';
import { PrismaModule } from '../prisma/prisma.module';
import { AuditLogModule } from '../audit-log/audit-log.module';
import { EMAIL_PROVIDER } from './email-provider.tokens';
import { ConsoleEmailProvider } from './console.email-provider';
import { NotificationService } from './notification.service';
import { ReminderService } from './reminder.service';
import { TaskService } from './task.service';
import { WorkspaceService } from './workspace.service';
import { CalendarService } from './calendar.service';
import { FavoritesService, RecentItemsService, SubscriptionService } from './personal.services';
import {
  CalendarController,
  FavoritesController,
  NotificationsController,
  RecentItemsController,
  RemindersController,
  SubscriptionsController,
  TasksController,
  WorkspaceController,
} from './productivity.controller';

/**
 * Phase 7.5 — productivity. Notifications are generated by the ReminderService
 * scanning existing QMS state, so no other module is modified. The email
 * provider is an interface — swap ConsoleEmailProvider for SMTP at the token.
 */
@Module({
  imports: [PrismaModule, AuditLogModule],
  controllers: [NotificationsController, RemindersController, TasksController, WorkspaceController, CalendarController, FavoritesController, RecentItemsController, SubscriptionsController],
  providers: [
    { provide: EMAIL_PROVIDER, useClass: ConsoleEmailProvider },
    NotificationService,
    ReminderService,
    TaskService,
    WorkspaceService,
    CalendarService,
    FavoritesService,
    RecentItemsService,
    SubscriptionService,
  ],
  exports: [NotificationService],
})
export class ProductivityModule {}
